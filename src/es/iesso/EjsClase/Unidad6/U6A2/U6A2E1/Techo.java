package es.iesso.EjsClase.Unidad6.U6A2.U6A2E1;

public class Techo {

    private int altura;
    private int color;

    public Techo(int altura, int color) {
        this.altura = altura;
        this.color = color;
    }

    public int getAltura() {
        return altura;
    }

    public int getColor() {
        return color;
    }
}
